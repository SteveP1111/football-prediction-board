#!/usr/bin/env python3
"""Daily immutable bookmaker edge publication with quota reservations.

Reads independent frozen model snapshots generated by scripts/refresh.py.
At most one paid attempt per UK date. A dated usage receipt is written before
the first chargeable request and retained even after a partial API error.
A workflow must commit data/edges even when this program exits unsuccessfully.
No raw bookmaker feed or API secret is ever added to Git.
"""
import argparse
import json
import os
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

from edge_comparison import DIVISION_SPORT, assess, fixture_kickoff, parse_utc
from edge_history import recalculate
from fetch_odds import collect, preflight

LONDON = ZoneInfo("Europe/London")
ROOT = Path(__file__).resolve().parents[1]
MAX_RUN_CREDITS = 12
RESERVE_CREDITS = 100
STANDARD_MARKET_COST = 2  # h2h + totals, one UK region
EXTRA_MARKET_COST = 2     # BTTS + alternate totals for one upcoming event


def json_data(path, default=None):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def write_json(path, document):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(document, indent=2, ensure_ascii=False,
                                    sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(path)


def eligible_games(snapshot, now):
    if not isinstance(snapshot, dict) or snapshot.get("status") != "frozen-prekickoff":
        return []
    today = now.astimezone(LONDON).date().isoformat()
    if snapshot.get("date") != today:
        return []
    captured = parse_utc(snapshot.get("capturedAt"))
    if not captured or captured >= now:
        return []
    items = []
    for item in snapshot.get("games", []):
        if item.get("division") not in DIVISION_SPORT or item.get("date") != today:
            continue
        kickoff = fixture_kickoff(item)
        if kickoff and kickoff > now + timedelta(minutes=15) and captured < kickoff:
            items.append(item)
    return items


def choose_spend(eligible, limit=MAX_RUN_CREDITS):
    sports = [DIVISION_SPORT[division] for division in DIVISION_SPORT
              if any(f["division"] == division for f in eligible)]
    base = len(sports) * STANDARD_MARKET_COST
    if base > limit:
        raise RuntimeError("Sport set exceeds daily hard credit budget")
    # At most two targeted event-market enquiries to preserve the 500-credit plan.
    extra = min(2, len(eligible), max(0, (limit - base) // EXTRA_MARKET_COST))
    return sports, extra, base + EXTRA_MARKET_COST * extra


def publish(root=ROOT, now=None, limit=MAX_RUN_CREDITS, reserve=RESERVE_CREDITS, dry_run=False):
    now = now or datetime.now(timezone.utc)
    if now.tzinfo is None:
        raise ValueError("now must be timezone-aware")
    if not 1 <= limit <= MAX_RUN_CREDITS or reserve < RESERVE_CREDITS:
        raise ValueError("Daily credit limit or monthly reserve exceeds permitted operating settings")
    today = now.astimezone(LONDON).date().isoformat()
    edges = root / "data" / "edges"
    snapshot_file = root / "data" / "latest.json"
    data = json_data(snapshot_file, {})
    archived = edges / "snapshots" / (today + ".json")
    receipt = edges / "usage" / (today + ".json")

    # Regrade verified results every run, even if today's odds have been frozen.
    recalculate(root)
    if receipt.exists():
        print("Odds request already attempted for", today, ": no further credits will be spent.")
        return "already-attempted"
    if archived.exists():
        print("Already have an immutable bookmaker snapshot for", today)
        return "already-snapshotted"
    eligible = eligible_games(data, now)
    if not eligible:
        print("No fresh frozen eligible fixtures today; skipping API entirely.")
        return "no-frozen-upcoming-games"
    sports, extra, projected = choose_spend(eligible, limit)
    if not sports:
        print("No supported divisions today; skipping API entirely.")
        return "no-supported-games"
    print("Daily edge plan:", today, "fixtures", len(eligible),
          "competitions", len(sports), "additional events", extra,
          "maximum planned credits", projected, "minimum reserve", reserve)
    if dry_run:
        return "dry-run"

    secret = os.environ.get("ODDS_API_KEY")
    if not secret:
        raise RuntimeError("ODDS_API_KEY not accessible")
    # No charge for the sports preflight; never create an attempted receipt
    # when no billable call is permitted due to quota or missing sport coverage.
    active, remaining = preflight(secret)
    if any(sport not in active for sport in sports):
        print("At least one required competition is inactive: no bookmaker requests made.")
        return "sport-inactive"
    if remaining - projected < reserve:
        print("Monthly API allowance reserve protects", reserve,
              "credits; no bookmaker requests made. Remaining:", remaining)
        return "quota-reserved"

    record = {
        "date": today, "status": "attempted",
        "startedAtUtc": now.isoformat(), "forecastCapturedAt": data["capturedAt"],
        "requestedSports": sports, "extraEventRequests": extra,
        "plannedMaxCredits": projected, "reserveCredits": reserve,
        "startRemaining": remaining, "endRemaining": remaining, "spentCredits": 0,
    }
    # Written BEFORE charging; the Actions workflow MUST persist this file even on failure.
    write_json(receipt, record)
    usage = {}
    try:
        fetched = collect(
            secret, sports, projected, save=False,
            extra_markets=("btts", "alternate_totals") if extra else (),
            extra_events=extra, frozen_snapshot=data,
            usage=usage, reserve_credits=reserve,
        )
        retrieved = datetime.now(timezone.utc).isoformat()
        report = assess(data, {
            "retrieved_at_utc": retrieved, "fixtures": fetched,
        })
        # Ensure there are no unknown result types or replayed prices.
        if report.get("forecastDate") != today or report.get("summary", {}).get("marketsPriced", 0) < 0:
            raise RuntimeError("Comparison failed basic validation")
        report["developmentPreview"] = False
        report["publishedAtUtc"] = datetime.now(timezone.utc).isoformat()
        report["priceType"] = "captured pre-kickoff quotation; not guaranteed executable"
        write_json(archived, report)
        # Latest is a replaceable pointer only; today's archive is never overwritten.
        write_json(edges / "latest.json", report)
        record["status"] = "complete"
        record["summary"] = report["summary"]
        print("Published confirmed comparisons:", report["summary"]["matchedFixtures"],
              "fixtures and", report["summary"]["marketsPriced"], "priced markets.")
        return "published"
    except Exception as exc:
        # API errors are sanitised by fetch_odds; avoid propagating new URLs or keys.
        record["status"] = "failed"
        record["reason"] = type(exc).__name__
        raise
    finally:
        record["completedAtUtc"] = datetime.now(timezone.utc).isoformat()
        if usage:
            for attr in ("endRemaining", "spentCredits"):
                if attr in usage:
                    record[attr] = usage[attr]
        write_json(receipt, record)
        if archived.exists():
            recalculate(root)
        print("Daily collection receipt:", today,
              "status", record["status"], "observed spend", record["spentCredits"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--limit", type=int, default=MAX_RUN_CREDITS)
    parser.add_argument("--reserve", type=int, default=RESERVE_CREDITS)
    args = parser.parse_args()
    try:
        publish(limit=args.limit, reserve=args.reserve, dry_run=args.dry_run)
    except Exception as exc:
        # Never include API URL, key or provider content in public errors.
        raise SystemExit("Production odds publishing failed; check the saved receipt. Type: " +
                         type(exc).__name__) from None


if __name__ == "__main__":
    main()
